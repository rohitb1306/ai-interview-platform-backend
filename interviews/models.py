import uuid

from django.db import models


class QuestionType(models.TextChoices):
    TECHNICAL = "TECHNICAL"
    BEHAVIORAL = "BEHAVIORAL"
    SYSTEM_DESIGN = "SYSTEM_DESIGN"


class InterviewToken(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    application = models.ForeignKey(
        "applications.Application", on_delete=models.CASCADE, related_name="tokens"
    )
    token_hash = models.CharField(max_length=255, unique=True)
    expires_at = models.DateTimeField()
    is_used = models.BooleanField(default=False)
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"Token for {self.application_id}"


class InterviewSession(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    application = models.ForeignKey(
        "applications.Application", on_delete=models.CASCADE, related_name="sessions"
    )
    started_at = models.DateTimeField(null=True, blank=True)
    completed_at = models.DateTimeField(null=True, blank=True)
    overall_score = models.DecimalField(max_digits=5, decimal_places=2, null=True)
    final_feedback = models.TextField(blank=True, null=True)

    def __str__(self):
        return f"Session {self.id} for {self.application_id}"


class InterviewQA(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    session = models.ForeignKey(
        InterviewSession, on_delete=models.CASCADE, related_name="qa_pairs"
    )
    question_text = models.TextField()
    question_type = models.CharField(max_length=20, choices=QuestionType.choices)
    candidate_answer_text = models.TextField(blank=True, null=True)
    evaluation_score = models.DecimalField(max_digits=5, decimal_places=2, null=True)
    ai_feedback = models.TextField(blank=True, null=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["created_at"]

    def __str__(self):
        return f"QA {self.id} ({self.question_type})"


class InterviewEventType(models.TextChoices):
    FOCUS_LOST = "FOCUS_LOST"  # switched tab/app or window lost focus
    FOCUS_RETURNED = "FOCUS_RETURNED"
    FULLSCREEN_EXIT = "FULLSCREEN_EXIT"
    RECORDING_ERROR = "RECORDING_ERROR"
    NO_FACE = "NO_FACE"  # no face in camera for a while (duration_ms = how long)
    MULTIPLE_FACES = "MULTIPLE_FACES"  # more than one face in camera (duration_ms = how long)
    CAMERA_LOST = "CAMERA_LOST"  # camera/mic stream ended mid-interview
    FACE_CHECK_UNAVAILABLE = "FACE_CHECK_UNAVAILABLE"  # face detector failed to load


class InterviewEvent(models.Model):
    """Integrity log captured by the interview room for human review."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    session = models.ForeignKey(InterviewSession, on_delete=models.CASCADE, related_name="events")
    qa = models.ForeignKey(
        InterviewQA, on_delete=models.SET_NULL, null=True, blank=True, related_name="events"
    )
    event_type = models.CharField(max_length=30, choices=InterviewEventType.choices)
    duration_ms = models.PositiveIntegerField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["created_at"]

    def __str__(self):
        return f"{self.event_type} in {self.session_id}"


class InterviewRecording(models.Model):
    """One continuous camera + microphone recording, uploaded in ordered chunks per question."""

    id = models.UUIDField(primary_key=True, editable=False)  # generated by the client
    session = models.ForeignKey(
        InterviewSession, on_delete=models.CASCADE, related_name="recordings"
    )
    qa = models.ForeignKey(InterviewQA, on_delete=models.CASCADE, related_name="recordings")
    file = models.FileField(upload_to="recordings/%Y/%m/")
    content_type = models.CharField(max_length=50)
    next_seq = models.PositiveIntegerField(default=0)
    size_bytes = models.PositiveIntegerField(default=0)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["created_at"]

    def __str__(self):
        return f"Recording {self.id} for QA {self.qa_id}"
